export function mealCost(budget: BudgetLevel, meal: boolean): number {
  if (meal) return budget === 'low' ? 120 : budget === 'premium' ? 600 : 250;
  return budget === 'low' ? 40 : budget === 'premium' ? 150 : 80;
}

export function stayRate(budget: BudgetLevel): number {
  return budget === 'low' ? 900 : budget === 'premium' ? 5000 : 2000;
}

export function fuelPerKm(mode: TravelMode): number {
  if (mode === 'car') return 7.5;
  if (mode === 'bike') return 2.4;
  return 0;
}

export function ticketPerKm(mode: TravelMode): number {
  if (mode === 'bus') return 1.8;
  if (mode === 'train') return 1.2;
  return 0;
}

export function tollPerKm(mode: TravelMode): number {
  if (mode === 'car') return 1.15;
  if (mode === 'bike') return 0.4;
  return 0;
}
